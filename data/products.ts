export function getProduct(slug: string): Product | undefined {
  return PRODUCTS.find((p) => p.slug === slug);
}

export function getVariant(product: Product, variantId?: string) {
  return product.variants?.find((v) => v.id === variantId);
}

/** Lowest offered price, considering variants. */
export function fromPrice(p: Product): { price: number; oldPrice?: number; hasRange: boolean } {
  if (!p.variants?.length) return { price: p.price, oldPrice: p.oldPrice, hasRange: false };
  const min = p.variants.reduce((a, v) => (v.price < a.price ? v : a), p.variants[0]);
  const hasRange = p.variants.some((v) => v.price !== min.price);
  return { price: min.price, oldPrice: hasRange ? undefined : min.oldPrice, hasRange };
}

export function isOnSale(p: Product): boolean {
  return !!p.oldPrice || !!p.variants?.some((v) => v.oldPrice);
}

export function productsInCategory(slug: string): Product[] {
  if (slug === "akciok") return PRODUCTS.filter(isOnSale);
  if (slug === "edzes-tipus")
    return PRODUCTS.filter((p) => p.category === "edzes-tipus" || (p.training?.length ?? 0) > 0);
  return PRODUCTS.filter((p) => p.category === slug);
}

/** Subcategory membership, accounting for "Edzés típus szerint" cross-listing. */
export function inSub(p: Product, category: string, sub: string): boolean {
  if (category === "edzes-tipus") return p.sub === sub || !!p.training?.includes(sub);
  return p.sub === sub;
}

export function relatedProducts(p: Product, count = 4): Product[] {
  const same = PRODUCTS.filter((x) => x.slug !== p.slug && x.category === p.category);
  const sameSub = same.filter((x) => x.sub === p.sub);
  const rest = same.filter((x) => x.sub !== p.sub);
  return [...sameSub, ...rest].slice(0, count);
}
