import type { Product, ResistanceLevel, Variant } from "@/lib/types";
import { RESISTANCE } from "./resistance";

/**
 * Mock catalog for the design concept.
 * `mock: false` → product name and prices come from the client brief (descriptions are newly written).
 * `mock: true`  → product, price and copy were invented for the concept.
 */

const bandVariants = (
  prefix: string,
  prices: Partial<Record<ResistanceLevel, number>>,
  backorder: ResistanceLevel[] = [],
  sale?: { level: ResistanceLevel; oldPrice: number },
): Variant[] =>
  RESISTANCE.filter((r) => prices[r.id] !== undefined).map((r) => ({
    id: `${prefix}-${r.id}`,
    label: `${r.name} · ${r.level}`,
    resistance: r.id,
    price: prices[r.id]!,
    oldPrice: sale?.level === r.id ? sale.oldPrice : undefined,
    stock: backorder.includes(r.id) ? "backorder" : "in_stock",
  }));

